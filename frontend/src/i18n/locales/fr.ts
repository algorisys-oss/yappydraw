/**
 * fr — translated from locales/en.ts.
 *
 * Typed as `Dictionary`, so a missing or invented key is a compile error rather
 * than a blank label found by a user.
 *
 * NOT translated, by rule (plan §3.3): keyboard shortcut letters, product and
 * standard names (YappyDraw, UML, BPMN, DFD, SVG), and API identifiers.
 *
 * Conventions chosen for this locale:
 *
 *  - **Terminology follows Illustrator/Photoshop FR**, so a user who knows the
 *    tool elsewhere recognises it here: fill and stroke are `fond` and `contour`,
 *    a layer is a `calque`, a path a `tracé`, rasterize is `pixelliser`, create
 *    outlines is `vectoriser`, and an artboard is a `plan de travail`. Z-order
 *    uses the four Illustrator verbs — `Premier plan`, `Rapprocher`, `Éloigner`,
 *    `Arrière-plan` — rather than a literal reading of "bring/send".
 *  - **Sentence case**, not English title case: French capitalises only the first
 *    word of a label. "Bring to Front" is `Premier plan`, not `Premier Plan`.
 *  - **A plain space before `:` `;` `!` `?`**, which French typography requires.
 *    A narrow no-break space would be more correct still, but an invisible
 *    character in source is a maintenance hazard, and a normal space is the
 *    ordinary choice in software localisation.
 *  - Emphasis in this header uses backticks, never asterisks: a `*` followed by
 *    a `/` closes the comment, and the first draft of this file did exactly that
 *    — `tsc` accepted it and the Vite dev server refused to serve it.
 *  - **Typographic apostrophe (’) throughout**, which is correct French and has
 *    the useful side effect that no string needs escaping inside single quotes.
 *  - **Guillemets « » for quoted text**, in place of English double quotes.
 *  - Infinitives for commands (`Annuler`, `Grouper`), as French menus do —
 *    never the imperative.
 */

