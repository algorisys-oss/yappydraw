/** Precompiled: normalized-key → normalized-token[]. */
const ALIASES: Record<string, string[]> = {};
for (const [k, toks] of Object.entries(RAW_ALIASES)) {
    ALIASES[norm(k)] = toks.map(norm);
}

/**
 * Extra concept tokens for a normalized query (spaceless lowercase). Returns the
 * alias tokens registered for the query, or `[]` when none exist. The caller
 * searches `[query, ...aliasesFor(query)]` across icon/illustration providers.
 */
export function aliasesFor(nq: string): string[] {
    return ALIASES[norm(nq)] ?? [];
}
